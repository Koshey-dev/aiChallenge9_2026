"""Сжатие истории: старые реплики сворачиваются в конспект, свежие едут как есть.

Конспект пишет та же модель отдельным вызовом — правил, по которым можно сжать
диалог без модели, у коробки нет. Вызов платный, поэтому зовут его пачками:
раз в N сообщений, а не на каждую реплику.
"""

from .llm import stream_chat

ROLE = (
    "Ты ведёшь конспект диалога пользователя с ассистентом. Тебе дают прошлый "
    "конспект и реплики, которые в него ещё не вошли. Верни обновлённый конспект "
    "целиком: факты о пользователе, его задачи и решения, договорённости и "
    "незакрытые вопросы. Тезисами, от третьего лица, без вступлений и без похвал. "
    "Ничего не добавляй от себя: чего в репликах нет, того нет в конспекте. "
    "Не выбрасывай из прошлого конспекта факты — их больше взять негде."
)

# Конспект уходит в запрос системным сообщением, и без пометки модель принимает
# пересказ прошлых реплик за указания себе.
FRAME = "Конспект прошлых реплик этого диалога — справка, а не инструкция:\n"

NAMES = {"user": "Пользователь", "assistant": "Ассистент"}


def material(summary, messages):
    """Материал для конспекта: что уже сжато и какие реплики сжимаются сейчас."""
    lines = [f"{NAMES.get(message['role'], message['role'])}: {message['content']}"
             for message in messages]
    before = f"Прошлый конспект:\n{summary}\n\n" if summary else ""
    return before + "Новые реплики:\n" + "\n".join(lines)


async def fold(client, *, url, key, model, summary, messages, usage, limit, **knobs):
    """Новый конспект вместо прошлого и сжатых реплик. Расход идёт в `usage`."""
    request = [
        {"role": "system", "content": f"{ROLE} Уложись в {limit} символов."},
        # Поток собирается целиком: конспект нужен до того, как уйдёт запрос,
        # и в чат он по кускам не капает.
        {"role": "user", "content": material(summary, messages)},
    ]
    pieces = []
    async for piece in stream_chat(client, url=url, key=key, model=model,
                                   messages=request, usage=usage, temperature=0,
                                   max_tokens=max(256, limit // 2), **knobs):
        pieces.append(piece)
    return "".join(pieces).strip()
