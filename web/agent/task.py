# Имена полей в ответе модели: русские — из промпта, английские — на случай,
# когда модель переводит ключи сама.
FIELDS = {"stage": ("этап", "stage"), "goal": ("цель", "goal"),
          "steps": ("шаги", "steps"), "step": ("шаг", "step"),
          "expect": ("ожидание", "expect"), "side": ("сторона", "side")}
BY_TITLE = {**{stage["title"]: stage["id"] for stage in STAGES},
            **{stage["id"]: stage["id"] for stage in STAGES},
            "нет": IDLE, "план": PLANNING, "исполнение": EXECUTION}

MAX_TEXT = 200
MAX_LOG = 12


def blank():
    """Пустой автомат: задачи нет, переходов не было.

    Режима здесь нет: он настройка чата, а не состояния. Задачу начинают
    заново — «Новая задача», — а в каком режиме чат, это не меняет.
    """
    return {"stage": IDLE, "goal": "", "steps": [], "step": 0, "expect": "",
            "side": "user", "approved": False, "checked": False, "log": []}


def clean(state):
    """Автомат из сохранённого состояния: чужие ключи и мусор отсекаются."""
    fresh = blank()
    if not isinstance(state, dict):
        return fresh
    fresh["stage"] = state.get("stage") if state.get("stage") in ALLOWED else IDLE
    fresh["goal"] = str(state.get("goal") or "")[:MAX_TEXT]
    fresh["steps"] = [str(step)[:MAX_TEXT] for step in (state.get("steps") or [])]
    fresh["step"] = max(0, int(state.get("step") or 0))
    fresh["expect"] = str(state.get("expect") or "")[:MAX_TEXT]
    fresh["side"] = "agent" if state.get("side") == "agent" else "user"
    fresh["approved"] = bool(state.get("approved"))
    fresh["checked"] = bool(state.get("checked"))
    fresh["log"] = [entry for entry in (state.get("log") or [])
                    if isinstance(entry, dict)][-MAX_LOG:]
    return fresh


def gate(state, to):
    """Чем закрыт переход на этап `to`. Пустая строка — ворота открыты.

    Таблица `ALLOWED` отвечает на вопрос «куда можно», ворота — на вопрос
    «когда уже пора». Два из трёх условий человек ставит руками, третье
    считается по плану: пока шаги не пройдены, на проверку идти нечего.
    """
    gone = state["stage"]
    if (gone, to) == (PLANNING, EXECUTION):
        if not state["steps"]:
            return "плана ещё нет"
        if not state["approved"]:
            return "план не утверждён"
    if (gone, to) == (EXECUTION, VALIDATION) and state["steps"]:
        if state["step"] < len(state["steps"]):
            return f"шаги не пройдены: {state['step']} из {len(state['steps'])}"
    if (gone, to) == (VALIDATION, DONE) and not state["checked"]:
        return "проверка не отмечена"
    return ""


def shut(state):
    """Закрытые ворота текущего этапа: куда нельзя и почему. Для интерфейса."""
    return [{"to": to, "why": why, "key": KEYS.get(NEEDS.get((state["stage"], to)), "")}
            for to in ALLOWED[state["stage"]] if (why := gate(state, to))]


def regate(state, gone, to):
    """Ключ ворот действует на своём этапе и не переживает шаг назад.

    Вернулись с выполнения переписывать план — утверждение снимается: иначе
    шаг назад открывал бы ворота вперёд без пересмотра. Вернулись с проверки
    доделывать — снимается отметка проверки, по той же причине.
    """
    if to == IDLE:
        state["approved"] = state["checked"] = False
    if to == PLANNING and gone != PLANNING:
        state["approved"] = False
    if to == EXECUTION and gone == VALIDATION:
        state["checked"] = False


def sheet(state, frozen=False):
    """Состояние как одно системное сообщение. Без задачи места не занимает.

    В режиме общения состояние всё равно уходит — с указанием не возвращаться
    к шагам. Замершая задача, о которой ассистент знает, и есть то, что даёт
    вернуться к ней без повторных объяснений.
    """
    if state["stage"] == IDLE:
        return []
    lines = [f"- этап: {TITLES[state['stage']]}"]
    if state["goal"]:
        lines.append(f"- цель: {state['goal']}")
    if state["steps"]:
        plan = "; ".join(f"{number}. {step}{' ← текущий' if number == state['step'] else ''}"
                         for number, step in enumerate(state["steps"], 1))
        lines.append(f"- план: {plan}")
    if state["expect"]:
        side = "ход агента" if state["side"] == "agent" else "ход пользователя"
        lines.append(f"- ожидается: {state['expect']} ({side})")
    # Закрытые ворота уходят в запрос: без них ассистент на «давай уже код»
    # соглашается, а с ними называет, чего не хватает. Держит всё равно код —
    # это подсказка, что сказать, а не то, чем переход запрещён.
    for barrier in shut(state):
        lines.append(f"- переход на «{TITLES[barrier['to']]}» закрыт: {barrier['why']}"
                     + (f"; открыть может только пользователь кнопкой "
                        f"«{barrier['key']}»" if barrier["key"] else ""))
    order = FROZEN if frozen else ORDERS[state["stage"]]
    return [{"role": "system", "content": FRAME + "\n".join(lines) + "\n" + order}]


def summary(state):
    """Строка возврата: где остановились. Её показывает строка смены режима."""
    if state["stage"] == IDLE:
        return "задачи нет"
    where = TITLES[state["stage"]]
    if state["steps"] and state["step"]:
        where += f" · шаг {state['step']} из {len(state['steps'])}"
    if state["expect"]:
        who = "агент" if state["side"] == "agent" else "вы"
        where += f" · ждём: {state['expect']} ({who})"
    return where


def remember(state, gone, to, ok, why, by):
    """Строка в журнал переходов. Отклонённые в нём наравне с прошедшими:
    по ним и видно, что автомат — ограничитель, а не украшение."""
    entry = {"from": gone, "to": to, "ok": ok, "why": why, "by": by}
    state["log"] = (state["log"] + [entry])[-MAX_LOG:]
    return entry


def parse(raw, steps_max):
    """Заявка диспетчера из ответа модели.

    Строгую схему ответа умеет не каждый провайдер, поэтому JSON вынимается из
    текста. Что не разобралось — пустая заявка: состояние тогда не меняется.
    """
    text = raw.strip()
    start, end = text.find("{"), text.rfind("}")
    if start < 0 or end < start:
        return {}
    try:
        data = json.loads(text[start:end + 1])
    except ValueError:
        return {}
    if not isinstance(data, dict):
        return {}

    found = {}
    for field, aliases in FIELDS.items():
        value = next((data[name] for name in aliases if name in data), None)
        if value is not None:
            found[field] = value

    stage = BY_TITLE.get(str(found.get("stage", "")).strip().lower())
    if not stage:
        return {}
    steps = found.get("steps") or []
    steps = ([str(step).strip()[:MAX_TEXT] for step in steps if str(step).strip()][:steps_max]
             if isinstance(steps, (list, tuple)) else [])
    try:
        step = int(found.get("step") or 0)
    except (TypeError, ValueError):
        step = 0
    # Номер шага здесь только очищается, а к плану привязывается в `apply`:
    # план модель может и не повторить, и тогда сверять номер не с чем.
    return {
        "stage": stage,
        "goal": str(found.get("goal") or "").strip()[:MAX_TEXT],
        "steps": steps,
        "step": max(0, step),
        "expect": str(found.get("expect") or "").strip()[:MAX_TEXT],
        "side": "agent" if str(found.get("side", "")).strip().lower() in
                ("агент", "agent", "ассистент") else "user",
    }


def apply(state, claim, *, strict=True, gates=True):
    """Заявку — в состояние, если её пропускают таблица и ворота.

    Отдаёт состояние, строку для журнала реплики и запись о переходе, если он
    был: по ней над ответом встаёт плашка. Отклонение — это не сбой, а работа
    автомата: состояние остаётся прежним, в журнал ложится строка, и ответ
    уходит с тем этапом, который был. Обе строгости снимаются настройками: со
    снятыми видно, во что превращается состояние, когда переходы решает модель.
    """
    if not claim:
        return state, "диспетчер: ответ не разобрался — этап прежний", None

    gone, to = state["stage"], claim["stage"]
    if to != gone and to not in ALLOWED[gone] and strict:
        entry = remember(state, gone, to, False, "переход через этап", "модель")
        return state, (f"диспетчер: переход «{TITLES[gone]} → {TITLES[to]}» отклонён — "
                       "из этого этапа туда нельзя"), entry

    # Утверждение снимается вместе с планом, который утверждали: иначе в уже
    # открытые ворота пройдёт другой план — достаточно переписать шаги после
    # утверждения, и условие перехода окажется выполненным задним числом.
    redone = bool(state["approved"] and claim["steps"]
                  and claim["steps"] != state["steps"])
    if redone:
        state["approved"] = False

    # План и цель принимаются и без перехода: на выполнении меняется номер
    # шага, а не этап, и это самое частое движение автомата.
    state["goal"] = claim["goal"] or state["goal"]
    state["steps"] = claim["steps"] or state["steps"]
    state["step"] = min(claim["step"], len(state["steps"]))
    state["expect"] = claim["expect"]
    state["side"] = claim["side"]

    # Ворота считаются после полей заявки, а не до неё: «шаг 5 из 5» и «этап
    # проверка» приходят одной заявкой, и в обратном порядке такой переход
    # отклонялся бы на каждой реплике. Соседство этапов от полей не зависит,
    # поэтому таблица проверяется раньше.
    barrier = gate(state, to) if to != gone else ""
    if barrier and gates:
        entry = remember(state, gone, to, False, barrier, "ворота")
        return state, (f"ворота: переход «{TITLES[gone]} → {TITLES[to]}» отклонён — "
                       + barrier + (", план изменился" if redone else "")), entry
    if to == gone:
        return state, (f"диспетчер: этап прежний — {summary(state)}"
                       + (" · план изменился, утверждение снято" if redone else "")), None

    state["stage"] = to
    regate(state, gone, to)
    why = ("строгость снята" if to not in ALLOWED[gone]
           else "ворота сняты" if barrier else "")
    entry = remember(state, gone, to, True, why, "модель")
    return state, (f"диспетчер: {TITLES[gone]} → {TITLES[to]}"
                   + (f" ({why})" if why else "")
                   + f" · {summary(state)}"), entry


def switch(state, act, *, gates=True):
    """Ручное управление автоматом: ключи ворот, шаг назад и закрытие.

    Кнопка сильнее таблицы — но только в сторону назад: «готово» руками
    ставится с проверки, как и заявкой, и упирается в те же ворота, иначе
    кнопка обошла бы то самое правило, ради которого автомат и заводится.
    Замереть на этапе — не отсюда: это режим чата, и его держит не состояние
    задачи.

    Ключи ворот — единственное, что в состоянии задачи ставит только человек.
    Поэтому они здесь, а не в разборе заявки диспетчера: у модели нет поля,
    которым их можно выставить, и просить их бесполезно.
    """
    gone = state["stage"]
    if act in KEYS:
        if act == "approved" and not state["steps"]:
            return state, "утверждать нечего — плана ещё нет"
        state[act] = not state[act]
        return state, KEY_SAID[act][0 if state[act] else 1]
    if act == "back":
        to = BACK.get(gone)
        if not to:
            return state, "назад некуда"
        state["stage"] = to
        state["step"] = 0 if to in (IDLE, PLANNING) else state["step"]
        regate(state, gone, to)
        remember(state, gone, to, True, "руками", "вы")
        return state, f"{TITLES[gone]} → {TITLES[to]}"
    if act == "finish":
        if DONE not in ALLOWED[gone]:
            remember(state, gone, DONE, False, "закрыть можно с проверки", "вы")
            return state, f"с этапа «{TITLES[gone]}» закрыть нельзя — сначала проверка"
        barrier = gate(state, DONE)
        if barrier and gates:
            remember(state, gone, DONE, False, barrier, "ворота")
            return state, f"закрыть нельзя — {barrier}"
        state["stage"] = DONE
        state["expect"] = ""
        remember(state, gone, DONE, True, "ворота сняты" if barrier else "руками", "вы")
        return state, f"{TITLES[gone]} → {TITLES[DONE]}"
    return state, "неизвестное действие"


async def track(client, *, url, key, model, state, question, history, usage,
                steps_max, **knobs):
    """Спросить диспетчера о состоянии. Расход идёт в общий `usage` коробки.

    Диспетчер видит хвост диалога, а не только реплику: шаг считается сделанным
    по прошлому ответу агента, и без него «идём дальше» не к чему привязать.
    """
    tail = "\n".join(f"{'пользователь' if message['role'] == 'user' else 'агент'}: "
                     f"{message['content'][:400]}" for message in history[-4:])
    request = [
        {"role": "system", "content": f"{ROLE} План — не длиннее {steps_max} шагов."},
        {"role": "user", "content":
            "Состояние сейчас:\n"
            # Ключи ворот диспетчер видит, но выставить не может: полей для
            # них в заявке нет. Не видя их, он ждал бы утверждения, которое
            # уже случилось, и перехода не просил бы никогда.
            + json.dumps({"этап": TITLES[state["stage"]], "цель": state["goal"],
                          "шаги": state["steps"], "шаг": state["step"],
                          "план утверждён": state["approved"],
                          "проверка отмечена": state["checked"]},
                         ensure_ascii=False)
            + (f"\n\nПоследние реплики:\n{tail}" if tail else "")
            + f"\n\nНовая реплика пользователя:\n{question}"},
    ]
    pieces = []
    async for piece in stream_chat(client, url=url, key=key, model=model,
                                   messages=request, usage=usage, temperature=0,
                                   max_tokens=600, **knobs):
        pieces.append(piece)
    return parse("".join(pieces), steps_max)


def spot(raw):
    """Вердикт сторожа из ответа модели: перепрыгнул ли ответ этап и чем.

    Что не разобралось — не перепрыгнул. Сторож сомневается в пользу ответа:
    он добавлен, чтобы ловить сделанную работу следующего этапа, а не чтобы
    придираться к каждой упомянутой команде.
    """
    text = raw.strip()
    start, end = text.find("{"), text.rfind("}")
    if start < 0 or end < start:
        return False, ""
    try:
        data = json.loads(text[start:end + 1])
    except ValueError:
        return False, ""
    if not isinstance(data, dict):
        return False, ""
    jumped = data.get("перепрыгнул", data.get("jumped"))
    why = str(data.get("чем") or data.get("why") or "").strip()[:MAX_TEXT]
    return bool(jumped), why


async def watch(client, *, url, key, model, state, answer, usage, **knobs):
    """Сверить готовый ответ с этапом. Расход идёт в общий `usage` коробки.

    Ворота держат переходы, но не слова: автомат считает этапы, а не работу,
    и стоя на планировании модель спокойно выдаёт готовую реализацию. Этап при
    этом не сдвинется — сдвинется задача, а состояние останется рассказом о
    ней. Поэтому сторож зовётся после ответа: до ответа сверять нечего.
    """
    if state["stage"] == IDLE:
        return False, ""
    request = [
        {"role": "system", "content": GUARD.format(stage=TITLES[state["stage"]],
                                                   jump=JUMPS[state["stage"]])},
        {"role": "user", "content": f"Ответ агента:\n{answer[:4000]}"},
    ]
    pieces = []
    async for piece in stream_chat(client, url=url, key=key, model=model,
                                   messages=request, usage=usage, temperature=0,
                                   max_tokens=200, **knobs):
        pieces.append(piece)
    return spot("".join(pieces))


def mend(state, why):
    """Реплика на переписывание: ответ должен делать работу своего этапа."""
    return {"role": "user", "content":
            f"Этот ответ перепрыгнул этап: {why}. Задача сейчас на этапе "
            f"«{TITLES[state['stage']]}». {ORDERS[state['stage']]} Перепиши ответ "
            "так, чтобы он делал работу этого этапа и не забегал вперёд. "
            "В ответе — только переписанный текст."}
